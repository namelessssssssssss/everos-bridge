"""Build-time Windows overlays. Canonical Unix sources are read-only inputs.

Every replacement checks its source anchor/count. An upstream platform change
must be reviewed here rather than silently applying a partial adapter.
"""


def replace(text, old, new, count=1):
    actual = text.count(old)
    if actual != count:
        raise ValueError("Windows compatibility anchor changed (expected {}, found {}): {}".format(count, actual, old[:100]))
    return text.replace(old, new)


def windows_rules(text):
    old = "运行源仓 `install.sh`"
    new = old + "（原生 Windows Codex/Kimi Code/Kimi Work 用 `install.ps1`）"
    if new in text:
        return text
    return replace(text, old, new)


def adapt(contents, lock_source):
    """Return generated bytes; never open any canonical source for writing."""
    from pathlib import Path
    result = dict(contents)
    for name in ("core.py", "hook.py", "recall.py"):
        path = Path("plugin/everos") / name
        text = result[path].decode("utf-8").replace("\r\n", "\n")
        text = replace(text, "import fcntl", "import windows_lock as fcntl")
        if name == "core.py":
            text = replace(text, 'open(sp.with_suffix(".lock"), "w")', 'open(sp.with_suffix(".lock"), "a+b")', 2)
            text = replace(text, 'open(STATE / "localmem.lock", "w")', 'open(STATE / "localmem.lock", "a+b")')
            text = replace(text, 'open(p.with_suffix(".lock"), "w")', 'open(p.with_suffix(".lock"), "a+b")')
        elif name == "recall.py":
            text = replace(text, 'open(path.with_suffix(".lock"), "a")', 'open(path.with_suffix(".lock"), "a+b")')
        else:
            text = replace(text, 'open(state_p.with_suffix(".lock"), "w")', 'open(state_p.with_suffix(".lock"), "a+b")')
            text = replace(text, '[sys.executable, str(Path(__file__).resolve()), "--worker"]',
                           '[sys.executable, "-X", "utf8", str(Path(__file__).resolve()), "--worker"]')
            text = replace(text, 'stderr=subprocess.DEVNULL, start_new_session=True,',
                           'stderr=subprocess.DEVNULL, creationflags=subprocess.CREATE_NO_WINDOW | subprocess.CREATE_NEW_PROCESS_GROUP,')
        compile(text, str(path), "exec")
        result[path] = text.encode("utf-8")
    path = Path("plugin/everos/rules.py")
    text = result[path].decode("utf-8")
    text = replace(text, '.read_text()', '.read_text(encoding="utf-8")', 3)
    result[path] = text.encode("utf-8")
    result[Path("plugin/everos/windows_lock.py")] = lock_source
    for path in (Path("plugin/rules/everos-rules.md"), Path("plugin/skills/everos-memory/SKILL.md")):
        result[path] = windows_rules(result[path].decode("utf-8")).encode("utf-8")
    return result
